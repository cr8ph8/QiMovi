/**
 * Shared jsPDF renderer — Cinema Aurea system.
 *
 * Every client-side PDF export must build its cover with `renderTitleBand()`
 * and its footer with `drawFooter()` so submission receipts, evidence
 * certificates, outlines, parity agreements, and rubric summaries share one
 * visual identity: a dark cover band with a gold display title, muted
 * subtitle, and quiet footer.
 *
 * All layout numbers, palette entries, font sizes, and stroke weights live
 * in the single `CINEMA_AUREA_SETTINGS` object below. Edit that object (or
 * call `configureCinemaAurea(partial)` at app boot) to restyle every PDF
 * export at once — do not hard-code new values inside helpers.
 *
 * Coordinate model: helpers work in whatever unit the passed `jsPDF` doc uses
 * (in, pt, mm) by converting internal pt offsets through `scaleFactor`. That
 * lets every existing exporter keep its own unit system while sharing this
 * cover.
 */

import { jsPDF } from "jspdf";
export type { jsPDF };

// ─── Types ────────────────────────────────────────────────────────────────

export type RGB = readonly [number, number, number];

export interface CinemaAureaPalette {
  /** Cover band background — near-black cinema. */
  bandBg: RGB;
  /** Primary gold — display type and hairline accents. */
  gold: RGB;
  /** Subtitle text on dark band. */
  subtitle: RGB;
  /** Body copy on white. */
  body: RGB;
  /** Muted metadata / footer text. */
  muted: RGB;
  /** Divider rule on light backgrounds. */
  rule: RGB;
}

/** All layout numbers are expressed in typographic points (pt). */
export interface CinemaAureaMetrics {
  /** Uniform page margin used by cover, footer, and rules. */
  marginPt: number;
  /** Vertical whitespace between the band and the first body element. */
  bodyGapPt: number;
  /** Footer baseline distance from bottom edge. */
  footerOffsetPt: number;
  /** Distance between page top and the eyebrow baseline. */
  bandEyebrowYPt: number;
  /** Distance between page top and the title baseline. */
  bandTitleYPt: number;
  /** Distance between page top and the subtitle baseline. */
  bandSubtitleYPt: number;
  /** Total height of the dark cover band. */
  bandHeightPt: number;
}

export interface CinemaAureaTypography {
  /** Font family used for every string drawn by shared helpers. */
  fontFamily: "helvetica" | "times" | "courier";
  eyebrowSizePt: number;
  titleSizePt: number;
  subtitleSizePt: number;
  bodySizePt: number;
  footerSizePt: number;
  /** Default section-heading size for `drawSectionHeading()`. */
  sectionHeadingSizePt: number;
}

export interface CinemaAureaStrokes {
  /** Gold hairline under the band and under section headings. */
  accentPt: number;
  /** Muted rule between body sections. */
  rulePt: number;
}

export interface CinemaAureaSettings {
  palette: CinemaAureaPalette;
  metrics: CinemaAureaMetrics;
  typography: CinemaAureaTypography;
  strokes: CinemaAureaStrokes;
  /** Default left-side footer attribution. */
  footerBrand: string;
}

